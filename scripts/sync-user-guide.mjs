import { readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import GithubSlugger from "github-slugger"

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(scriptDir, "..")
const guideDir = process.env.TASKFORCE_GUIDE_DIR
  ? path.resolve(process.env.TASKFORCE_GUIDE_DIR)
  : path.resolve(frontendRoot, "../EnderAI/docs/user-guide")
const outputPath = path.resolve(
  frontendRoot,
  "src/components/Docs/docs-content.generated.ts",
)

function parseFrontmatter(source, file) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!match) {
    throw new Error(`${file} is missing YAML frontmatter`)
  }

  const data = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const separator = line.indexOf(":")
      if (separator === -1) {
        throw new Error(`Invalid frontmatter line in ${file}: ${line}`)
      }
      return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()]
    }),
  )

  return { data, body: match[2].trimEnd() }
}

function plainHeading(markdown) {
  return markdown
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[*_~]/g, "")
    .trim()
}

function headingsFor(body) {
  const slugger = new GithubSlugger()
  return Array.from(body.matchAll(/^(#{2,3})\s+(.+)$/gm), (match) => {
    const text = plainHeading(match[2])
    return {
      id: slugger.slug(text),
      text,
      level: match[1].length,
    }
  })
}

const files = (await readdir(guideDir))
  .filter((file) => /^\d{2}-.*\.md$/.test(file))
  .sort()

const pages = await Promise.all(
  files.map(async (file) => {
    const source = await readFile(path.join(guideDir, file), "utf8")
    const { data, body } = parseFrontmatter(source, file)
    const order = Number(data.order)

    if (
      !data.title ||
      !data.slug ||
      !Number.isInteger(order) ||
      !["all", "developer", "champion"].includes(data.audience)
    ) {
      throw new Error(`Invalid frontmatter contract in ${file}`)
    }

    return {
      file,
      title: data.title,
      slug: data.slug,
      order,
      audience: data.audience,
      body,
      headings: headingsFor(body),
    }
  }),
)

const generated = `// Generated by scripts/sync-user-guide.mjs from EnderAI/docs/user-guide.
// The backend repository remains the canonical, hand-edited documentation source.

export type DocsAudience = "all" | "developer" | "champion"

export type DocsHeading = {
  id: string
  text: string
  level: 2 | 3
}

export type DocsPage = {
  file: string
  title: string
  slug: string
  order: number
  audience: DocsAudience
  body: string
  headings: DocsHeading[]
}

export const DOCS_PAGES: DocsPage[] = ${JSON.stringify(pages, null, 2)}

export const DOCS_BY_SLUG = Object.fromEntries(
  DOCS_PAGES.map((page) => [page.slug, page]),
) as Record<string, DocsPage>

export const DOCS_LINK_MAP = Object.fromEntries(
  DOCS_PAGES.map((page) => [page.file, page.slug]),
) as Record<string, string>
`

await writeFile(outputPath, generated)
console.log(`Wrote ${path.relative(frontendRoot, outputPath)} from ${guideDir}`)
